export const GLYPH_HEIGHT = 7;

const GLYPHS: Record<string, boolean[][]> = Object.fromEntries(
  Object.entries(RAW).map(([ch, s]) => [ch, s.split('|').map((r) => [...r].map((c) => c === '#'))]),
);

function glyph(ch: string): boolean[][] {
  return GLYPHS[ch.toUpperCase()] ?? GLYPHS['?']!;
}

export function hasGlyph(ch: string): boolean {
  return ch.toUpperCase() in GLYPHS;
}

export function textWidth(text: string, scale = 1, spacing = 1): number {
  const chars = [...text];
  let w = 0;
  chars.forEach((ch, i) => {
    w += glyph(ch)[0]!.length * scale;
    if (i < chars.length - 1) w += spacing * scale;
  });
  return w;
}

/** Draws text with its top-left at (x, y). Lowercase is drawn as uppercase. */
export function drawText(buf: PixelBuffer, text: string, x: number, y: number, color: Color, scale = 1, spacing = 1): void {
  let cx = Math.round(x);
  for (const ch of text) {
    const g = glyph(ch);
    for (let gy = 0; gy < g.length; gy++) {
      for (let gx = 0; gx < g[gy]!.length; gx++) {
        if (!g[gy]![gx]) continue;
        buf.rect(cx + gx * scale, y + gy * scale, cx + gx * scale + scale - 1, y + gy * scale + scale - 1, color);
      }
    }
    cx += (g[0]!.length + spacing) * scale;
  }
}

/** Text with a 1px (×scale) outline on all sides. */
export function drawOutlinedText(
  buf: PixelBuffer,
  text: string,
  x: number,
  y: number,
  fill: Color,
  outline: Color,
  scale = 1,
): void {
  for (let dy = -1; dy <= 1; dy++) {
    for (let dx = -1; dx <= 1; dx++) {
      if (dx || dy) drawText(buf, text, x + dx * scale, y + dy * scale, outline, scale);
    }
  }
  drawText(buf, text, x, y, fill, scale);
}
